if (mode === "web") {
	mkdirSync("web/dist", { recursive: true });
	const hash = createHash("sha256").update(readFileSync("esbuild.config.mjs"));
	for (const dir of ["src", "web", "preview", "server"]) {
		for (const name of readdirSync(dir).sort().filter(name => /\.(ts|html|py)$/.test(name))) hash.update(readFileSync(`${dir}/${name}`));
	}
	hash.update(readFileSync("styles.css"));
	const build = hash.digest("hex").slice(0, 16);
	const result = await esbuild.build({
		entryPoints: ["web/main.ts"],
		alias: { obsidian: "./scripts/obsidian-stub.ts" },
		define: { __WEB_BUILD__: JSON.stringify(build) },
		bundle: true, platform: "browser", format: "iife", minify: true,
		outdir: "web/dist", entryNames: "web-[hash]", metafile: true, logLevel: "info",
	});
	const js = Object.keys(result.metafile.outputs).find(name => name.endsWith(".js"));
	if (!js) throw new Error("Missing web bundle");
	const cssResult = await esbuild.transform(readFileSync("styles.css", "utf8"), { loader: "css", minify: true });
	const css = cssResult.code;
	const html = readFileSync("web/index.html", "utf8")
		.replace(/<link rel="stylesheet" href="(?:\.\.\/|\.\/)styles\.css[^"]*"\s*\/>/, () => `<style id="cpo-app-styles">${css}</style>`)
		.replaceAll("./web.js", `./${js.split("/").pop()}`);
	writeFileSync("web/dist/index.html", html);
	const source = readFileSync(js);
	writeFileSync(`${js}.br`, brotliCompressSync(source));
	writeFileSync(`${js}.gz`, gzipSync(source, { level: 9 }));
	writeFileSync("web/dist/version.json", JSON.stringify({ build, api: 2, minClientApi: 2 }));
	process.exit(0);
}

