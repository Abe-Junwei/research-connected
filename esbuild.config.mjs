import esbuild from "esbuild";
import { mkdirSync, readFileSync, writeFileSync, readdirSync } from "node:fs";
import process from "process";
import { createHash } from "node:crypto";
import { builtinModules } from "node:module";
import { brotliCompressSync, gzipSync } from "node:zlib";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the repository of this plugin.
*/
`;

const mode = process.argv[2] ?? "dev";

if (mode === "node-limits") {
	await esbuild.build({
		entryPoints: ["scripts/evaluate-node-limits.ts"],
		alias: { obsidian: "./scripts/obsidian-stub.ts" },
		bundle: true, platform: "node", format: "cjs",
		outfile: "scripts/evaluate-node-limits.cjs", logLevel: "info",
	});
	process.exit(0);
}

