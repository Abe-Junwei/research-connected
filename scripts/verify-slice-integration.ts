import assert from "node:assert/strict";
import { nicholsSnapshot } from "../preview/work-identity-fixture";
import { applyWorkIdentityDecisions } from "../src/graph-edit";
import { emptyFilter } from "../src/graph-filter";
import { graphExportVersions } from "../src/export-graph";
import { changeVersionExclusion, commitSourceVersionRelations, commitWorkIdentityDecision, composeProjectGraph, normalizeProjects, projectVersionGraph, projectVersionNode, projectVersionState, resolveProjectPending, restoreGraphSnapshot, saveGraphSnapshot, type ResearchProject } from "../src/project-state";
import { DEFAULT_SETTINGS, type ConnectedPapersSettings } from "../src/settings-model";
import { CrossrefClient, type CrossrefWork } from "../src/citation-sources";
import { createReadingWorkflow } from "../src/reading-workflow";
import { normalizeDoi } from "../src/paper";
import type { SourceVersionRelation } from "../src/work-identity";

export async function verifySliceIntegration(): Promise<void> {
	const graph = restoreGraphSnapshot(nicholsSnapshot())!;
	const [seed, alias] = graph.nodes;
	assert.ok(seed && alias);
	const project: ResearchProject = { version: 1, seedId: seed.id, name: "Project", updatedAt: 1, views: [], snapshot: saveGraphSnapshot(graph) };
	const settings = { ...DEFAULT_SETTINGS, researchProjects: { W1: structuredClone(project), W2: structuredClone(project) } };
	const decision = { ids: [seed.id, alias.id], kind: "merge" as const, source: "manual" as const, updatedAt: 2 };
	await commitWorkIdentityDecision(settings, decision, async () => {});
	for (const saved of Object.values(settings.researchProjects)) assert.equal(restoreGraphSnapshot(saved.snapshot)!.nodes.length, 1, "manual merge propagates to every saved project");
	const before = settings.researchProjects;
	await assert.rejects(commitWorkIdentityDecision(settings, { ...decision, kind: "separate" }, async () => { throw new Error("disk full"); }), /disk full/);
	assert.equal(settings.researchProjects, before, "failed global identity save preserves all prior projects");
	await commitWorkIdentityDecision(settings, { ...decision, kind: "clear" }, async () => {});
	for (const saved of Object.values(settings.researchProjects)) assert.equal(restoreGraphSnapshot(saved.snapshot)!.nodes.length, 2, "undoing the manual merge restores distinct DOI records");

	const merged = applyWorkIdentityDecisions(graph, [decision]);
	const whole = { ...project, seedId: "W9" };
	changeVersionExclusion(whole, alias, true, true, merged.nodes[0]!);
	assert.equal(projectVersionState(whole, seed).excluded, true);
	changeVersionExclusion(whole, alias, false, false, merged.nodes[0]!);
	assert.equal(projectVersionState(whole, alias).excluded, false, "one-version restore overrides whole exclusion");
	assert.equal(projectVersionState(whole, seed).excluded, true, "restore retains sibling exclusion");
	assert.throws(() => changeVersionExclusion(project, seed, true, false), /seed|起点/);
	const sideProject = { ...structuredClone(project), seedId: "W9" };
	changeVersionExclusion(sideProject, alias, true, true);
	const scopeSettings = { ...DEFAULT_SETTINGS, researchProjects: { W1: sideProject } };
	await commitWorkIdentityDecision(scopeSettings, decision, async () => {});
	assert.equal(projectVersionState(scopeSettings.researchProjects.W1!, seed).excluded, false, "merging an excluded side does not exclude the other known side");
	assert.equal(projectVersionState(scopeSettings.researchProjects.W1!, alias).excluded, true);
	const mixed = scopeSettings.researchProjects.W1!;
	const newcomer = { ...alias, id: "W777", doiUrl: "https://doi.org/10.1234/unknown-side", isSeed: false };
	const extended = applyWorkIdentityDecisions({ ...graph, nodes: [...graph.nodes, newcomer], catalog: [...graph.catalog, newcomer] }, [{ ...decision, ids: [...decision.ids, newcomer.id] }]);
	projectVersionGraph(extended, mixed);
	assert.equal(mixed.pending?.length, 1, "an unknown new version after a mixed-side merge requires scope confirmation");
	projectVersionGraph(extended, mixed);
	assert.equal(mixed.pending?.length, 1, "projection does not duplicate pending scope records");
	const pendingId = mixed.pending![0]!.id;
	await assert.rejects(resolveProjectPending(scopeSettings, "W1", pendingId, "visible", async () => { throw new Error("disk full"); }), /disk full/);
	assert.equal(scopeSettings.researchProjects.W1, mixed, "failed scope confirmation retains the pending record");
	await resolveProjectPending(scopeSettings, "W1", pendingId, "visible", async () => {});
	assert.equal(scopeSettings.researchProjects.W1!.pending?.length, 0);
	projectVersionGraph(extended, scopeSettings.researchProjects.W1);
	assert.equal(scopeSettings.researchProjects.W1!.pending?.length, 0, "confirmed scope does not ask again on refresh");
	await commitWorkIdentityDecision(scopeSettings, { ...decision, kind: "separate" }, async () => {});
	assert.equal(projectVersionState(scopeSettings.researchProjects.W1!, seed).excluded, false);
	assert.equal(projectVersionState(scopeSettings.researchProjects.W1!, alias).excluded, true, "splitting retains each side's exclusion flags");
	assert.equal(scopeSettings.researchProjects.W1!.exclusionScopes?.find(entry => entry.ids.includes(alias.id))?.scope.wholeExcluded, true, "split restores the excluded side's future-version rule");
	const originScope = structuredClone(mixed);
	originScope.pending = [];
	const sourceOrigin: SourceVersionRelation = { ids: [alias.id, newcomer.id], status: "confirmed", source: "crossref", linked: true, evidence: ["crossref:is-version-of"], updatedAt: 5 };
	const sourced = applyWorkIdentityDecisions({ ...graph, nodes: [...graph.nodes, newcomer], catalog: [...graph.catalog, newcomer] }, [decision], [sourceOrigin]);
	projectVersionGraph(sourced, originScope);
	assert.equal(projectVersionState(originScope, newcomer).excluded, true, "a source linking a future version to the excluded original side inherits its whole-work rule");
	assert.equal(originScope.pending.length, 0, "known source origin needs no scope guess");

	const doiA = normalizeDoi(seed.doiUrl)!, doiB = normalizeDoi(alias.doiUrl)!;
	let payload: CrossrefWork = { DOI: doiA, relation: { "is-preprint-of": [{ id: doiB, "id-type": "doi" }] } };
	const crossref = new CrossrefClient(async url => ({ message: url.includes(encodeURIComponent(doiA).replace(/%2F/gi, "/")) ? payload : { DOI: doiB } }), "");
	const reports = await crossref.versionRelations([seed, alias]);
	assert.equal(reports[0]?.status, "confirmed", "explicit Crossref version links are production identity evidence");
	const sourceSettings: ConnectedPapersSettings = { ...DEFAULT_SETTINGS, researchProjects: { W1: structuredClone(project), W2: structuredClone(project) } };
	const reading = createReadingWorkflow({ getSettings: () => sourceSettings, persist() {} });
	await reading.commitWorkflow(seed, null, { reading: "unread" });
	await reading.commitWorkflow(alias, null, { reading: "read" });
	await assert.rejects(commitSourceVersionRelations(sourceSettings, reports, async () => { throw new Error("disk full"); }), /disk full/);
	assert.equal(sourceSettings.sourceVersionRelations?.length ?? 0, 0, "failed source save does not publish an unpersisted identity");
	assert.equal(restoreGraphSnapshot(sourceSettings.researchProjects.W1!.snapshot)!.nodes.length, 2);
	await commitSourceVersionRelations(sourceSettings, reports, async () => {});
	for (const saved of Object.values(sourceSettings.researchProjects)) assert.equal(restoreGraphSnapshot(saved.snapshot)!.nodes.length, 1, "source facts propagate to all saved projects");
	assert.equal(reading.getReadingState(seed).reading, "read", "raw-version reading respects the source-confirmed group");
	await reading.commitWorkflow(seed, null, { reading: "unread" });
	assert.equal(reading.getReadingState(alias).reading, "unread", "source-confirmed reading still accepts an explicit downgrade");
	await commitWorkIdentityDecision(sourceSettings, { ...decision, kind: "separate" }, async () => {});
	assert.equal(restoreGraphSnapshot(sourceSettings.researchProjects.W1!.snapshot)!.nodes.length, 2, "manual separation overrides a source link");
	await commitWorkIdentityDecision(sourceSettings, { ...decision, kind: "clear" }, async () => {});
	assert.equal(restoreGraphSnapshot(sourceSettings.researchProjects.W1!.snapshot)!.nodes.length, 1, "clearing a manual choice resumes current source evidence");
	// An explicit relation check refreshes metadata instead of reusing the reference/abstract cache.
	const refreshClient = () => new CrossrefClient(async url => ({ message: url.includes(encodeURIComponent(doiA).replace(/%2F/gi, "/")) ? payload : { DOI: doiB } }), "");
	payload = { DOI: doiA };
	const missing = await refreshClient().versionRelations([seed, alias], sourceSettings.sourceVersionRelations);
	await commitSourceVersionRelations(sourceSettings, missing, async () => {});
	assert.equal(sourceSettings.sourceVersionRelations?.[0]?.linked, true, "one missing relation never silently splits a confirmed group");
	assert.ok(sourceSettings.sourceVersionRelations?.[0]?.previousEvidence?.length, "missing reports retain original evidence");
	assert.equal(sourceSettings.researchProjects.W1!.pending?.[0]?.kind, "identity");
	payload = { DOI: doiA, relation: { "is-review-of": [{ id: doiB, "id-type": "doi" }] } };
	const conflict = await refreshClient().versionRelations([seed, alias], sourceSettings.sourceVersionRelations);
	await commitSourceVersionRelations(sourceSettings, conflict, async () => {});
	assert.equal(sourceSettings.sourceVersionRelations?.[0]?.status, "conflict", "contrary inter-work evidence freezes a version link for review rather than inventing a denial");
	assert.equal(restoreGraphSnapshot(sourceSettings.researchProjects.W1!.snapshot)!.nodes.length, 1);
	const negative: SourceVersionRelation = { ...conflict[0]!, status: "negated", linked: false, evidence: ["explicit-denial-fixture"], updatedAt: Date.now() + 1 };
	await assert.rejects(commitSourceVersionRelations(sourceSettings, [negative], async () => { throw new Error("disk full"); }), /disk full/);
	assert.equal(sourceSettings.sourceVersionRelations?.[0]?.linked, true, "failed denial save retains the old shared identity");
	await commitSourceVersionRelations(sourceSettings, [negative], async () => {});
	assert.equal(restoreGraphSnapshot(sourceSettings.researchProjects.W1!.snapshot)!.nodes.length, 2);
	await reading.commitWorkflow(seed, null, { reading: "read" });
	assert.equal(reading.getReadingState(alias).reading, "unread", "a split preserves inherited progress and lets versions change independently");
	let repeatedSaves = 0;
	await commitSourceVersionRelations(sourceSettings, reports, async () => { repeatedSaves++; });
	assert.equal(repeatedSaves, 0, "a delayed older report cannot restore a denied source link");
	const transitive: ConnectedPapersSettings = { ...DEFAULT_SETTINGS, researchProjects: { W1: { ...structuredClone(project), snapshot: saveGraphSnapshot({ ...graph, nodes: [...graph.nodes, newcomer], catalog: [...graph.catalog, newcomer] }) } } };
	const transitiveReading = createReadingWorkflow({ getSettings: () => transitive, persist() {} });
	await transitiveReading.commitWorkflow(seed, null, { reading: "unread" });
	await transitiveReading.commitWorkflow(alias, null, { reading: "unread" });
	await transitiveReading.commitWorkflow(newcomer, null, { reading: "read" });
	transitive.sourceVersionRelations = [reports[0]!, sourceOrigin];
	transitive.workIdentityDecisions = [decision];
	assert.equal(transitiveReading.getReadingState(newcomer).reading, "read", "source and manual links form the same transitive group for reading");
	await transitiveReading.commitWorkflow(seed, null, { reading: "unread" });
	assert.equal(transitiveReading.getReadingState(newcomer).reading, "unread", "a manual pair does not sever a third source-confirmed version's shared reading");
	assert.throws(() => normalizeProjects({ W1: { ...project, exclusionScopes: [{ ids: [alias.id], scope: { wholeExcluded: false, versions: {}, wholeRules: [[3]] } }] } }), /provenance|排除来源记录/);

	const alternate = { ...alias, year: 2025, language: "fr", workType: "preprint", isSeed: false };
	const versions = { ...seed, isSeed: false, records: [{ ...seed, isSeed: false }, alternate] };
	const source = { ...graph, nodes: [versions], catalog: [versions], workIdentity: undefined, referenceLists: new Map([[seed.id, ["W100"]], [alias.id, ["W200"]]]) };
	const canonical = applyWorkIdentityDecisions(source, [decision]);
	const filter = { ...emptyFilter(), language: "fr" };
	const shown = projectVersionGraph(canonical, undefined, filter);
	assert.equal(shown.nodes[0]?.language, "fr", "filtered version supplies all display fields");
	assert.equal(shown.nodes[0]?.year, 2025);
	assert.deepEqual(projectVersionNode(canonical.nodes[0]!, undefined, filter), shown.nodes[0], "detail version selection matches the graph without rebuilding relations");
	assert.equal(projectVersionNode(canonical.nodes[0]!, undefined, { ...filter, language: "de" }), null);
	const excluded = structuredClone(project);
	changeVersionExclusion(excluded, alternate, true, false, canonical.nodes[0]!);
	assert.deepEqual(projectVersionNode(canonical.nodes[0]!, excluded, filter), projectVersionGraph(canonical, excluded, filter).nodes[0] ?? null);
	assert.deepEqual(shown.referenceLists.get(shown.nodes[0]!.id), ["W200"], "ineligible sibling relations are not reintroduced during derived-score refresh");
	const seedFiltered = projectVersionGraph(graph, project, { ...emptyFilter(), language: "fr" });
	assert.equal(seedFiltered.nodes.length, 1, "seed display exception remains visible");
	assert.equal(seedFiltered.edges.length, 0, "seed display exception has no relations");
	assert.equal(graphExportVersions(graph.nodes, project, { ...emptyFilter(), language: "fr" }, "one", false).length, 0);
	assert.equal(graphExportVersions(graph.nodes, project, { ...emptyFilter(), language: "fr" }, "one", true).length, 1);

	const explicit = Array.from({ length: 310 }, (_, index) => ({ ...alias, id: `W${9000 + index}`, doiUrl: null }));
	const composed = composeProjectGraph(graph, { ...project, sampleIds: graph.nodes.map(node => node.id), manualPapers: explicit }, 20);
	assert.equal(composed.nodes.length, 312, "automatic cap does not discard explicit retained members");
	const reloaded = normalizeProjects({ W1: { ...project, snapshot: saveGraphSnapshot(composed), manualPapers: explicit } });
	assert.equal(reloaded.W1?.snapshot?.nodes.length, 312, "explicit members survive settings reload above the automatic cap");
}
