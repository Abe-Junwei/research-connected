import assert from "node:assert/strict";
import vm from "node:vm";
import { build } from "esbuild";

const code = (await build({ entryPoints: ["web/project-store.ts"], alias: { obsidian: "./scripts/obsidian-stub.ts" }, bundle: true, format: "cjs", platform: "browser", write: false })).outputFiles[0].text;
const data = new Map(); let failWrite = false, queue = Promise.resolve();
const storage = { getItem: key => data.get(key) ?? null, setItem: (key, value) => { if (failWrite) throw new DOMException("full", "QuotaExceededError"); data.set(key, value); } };
const module = { exports: {} };
vm.runInNewContext(code, { module, exports: module.exports, window: { localStorage: storage }, navigator: { locks: { request: (_key, callback) => { const next = queue.then(callback); queue = next.catch(() => {}); return next; } } }, structuredClone, DOMException, Date, URL, Set, Map });
const { createWebSettingsStore, loadWebSettings } = module.exports;
const project = id => ({ version: 1, seedId: id, name: id, updatedAt: 1, views: [], deepDives: [{ id: "1", parentId: id, createdAt: 1, references: 0, citations: 0, additions: [], noMore: true, warnings: [] }] });
storage.setItem("settings", JSON.stringify({ researchProjects: { W1: project("W1"), W2: project("W2") } }));
const a = loadWebSettings("settings"), b = loadWebSettings("settings");
const sa = createWebSettingsStore("settings", a, () => {}), sb = createWebSettingsStore("settings", b, () => {});
a.researchProjects.W1.name = "A saved";
b.researchProjects.W2.name = "B saved";
await Promise.all([sa.persist(), sb.persist()]);
assert.equal(loadWebSettings("settings").researchProjects.W1.name, "A saved");
assert.equal(loadWebSettings("settings").researchProjects.W2.name, "B saved");
const stale = loadWebSettings("settings"), staleStore = createWebSettingsStore("settings", stale, () => {});
a.researchProjects.W1.name = "Newest"; await sa.persist();
stale.researchProjects.W1.name = "Late overwrite";
await assert.rejects(staleStore.persist(), /另一标签页/);
assert.equal(stale.researchProjects.W1.name, "Newest");
assert.equal(loadWebSettings("settings").researchProjects.W1.name, "Newest");
const before = storage.getItem("settings");
failWrite = true;
a.researchProjects.W1.name = "Unsaved";
await assert.rejects(sa.persist(), error => error.name === "StorageFullError");
assert.equal(storage.getItem("settings"), before);
assert.equal(a.researchProjects.W1.name, "Newest", "Failed save must roll memory back too");
failWrite = false;
const readonly = loadWebSettings("settings"), sr = createWebSettingsStore("settings", readonly, () => { throw new Error("read-only"); });
readonly.researchProjects.W1.name = "Stolen";
await assert.rejects(sr.persist(), /read-only/);
assert.equal(storage.getItem("settings"), before);
console.log("Web project store: concurrent distinct projects merge; stale peer/read-only/full-storage writes rejected; memory and disk preserved: passed");
