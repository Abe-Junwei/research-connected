import assert from "node:assert/strict";
import { bindLanguage } from "../src/i18n";
import { readHostLanguage } from "../src/host-language";
import { graphExportVersions, literatureFilename, literatureMarkdown, orderedForExport, toBibTeX, toMarkdownTable, toYamlList } from "../src/export-graph";
import { emptyFilter } from "../src/graph-filter";
import type { PaperNode } from "../src/types";
import { updateProjectPaperState, type ResearchProject } from "../src/project-state";

export function verifyExport(): void {
	const paper: PaperNode = { id: "W1", title: "A {B} \\ C & 50%_#~^", authors: "Ada & Bob", authorList: ["Ada & Bob", "王明"], year: 2020, citedByCount: 0, citationCountStatus: "known", abstract: "", doiUrl: "https://doi.org/10.1234/example", openAlexUrl: "https://openalex.org/W1", isSeed: true, origin: "seed", language: "en", workType: "article", venue: "Journal", concepts: [], retracted: false };
	const missing = { ...paper, id: "W2", isSeed: false, year: null, citationCountStatus: "missing" as const, doiUrl: null };
	const before = JSON.stringify([paper, missing]);
	const keys = toBibTeX([paper, { ...paper, id: "W10001" }, { ...paper, id: "W20001" }, paper]).match(/^@\w+\{([^,]+)/gm)!;
	assert.equal(new Set(keys).size, 4, "citation keys remain unique after repeated suffix collisions");
	assert.match(toBibTeX([paper]), /A \\\{B\\\} \\textbackslash\{\} C \\& 50\\%\\_\\#\\textasciitilde\{\}\\textasciicircum\{\}/, "BibTeX preserves literal punctuation and escapes TeX commands");
	assert.match(toBibTeX([paper]), /author = \{Ada \\& Bob and 王明\}/);
	assert.match(toBibTeX([paper]), /journal = \{Journal\}/, "known journal names are not discarded");
	assert.match(toBibTeX([{ ...paper, workType: "book-chapter" }]), /booktitle = \{Journal\}/);
	assert.match(toBibTeX([{ ...paper, bibliography: { volume: "12", issue: "3", firstPage: "10", lastPage: "20" } }]), /volume = \{12\},\n  number = \{3\},\n  pages = \{10--20\}/);
	for (const [workType, expected] of [["book", "book"], ["book-chapter", "incollection"], ["dissertation", "phdthesis"], ["article", "article"], ["preprint", "article"], [null, "misc"]] as const) assert.ok(toBibTeX([{ ...paper, workType }]).startsWith(`@${expected}{`));
	assert.equal(toBibTeX([]), "");
	assert.equal(toYamlList([]), "papers: []", "empty YAML is an empty list, not null");
	assert.match(toYamlList([paper, missing]), /citations: 0[\s\S]*year: null\n    citations: null/);
	const special = { ...paper, title: '中文 "quoted"\nsecond\tline | \\ path\rthird' };
	assert.equal(JSON.parse(toYamlList([special]).split("\n")[1]!.split("title: ")[1]!), special.title, "YAML quoted scalars preserve special characters");
	const table = toMarkdownTable([special]);
	assert.equal(table.split("\n").length, 3, "embedded line breaks cannot create extra table rows");
	assert.ok(!table.includes("\r"), "carriage returns are normalized in table cells");
	assert.ok(table.includes("\\|"));
	assert.deepEqual(orderedForExport([missing, { ...paper, id: "W3", isSeed: false, year: 1990 }, paper]).map(p => p.id), ["W1", "W2", "W3"]);
	const versions = [{ ...paper, id: "W3", isSeed: false, workType: "preprint", year: 2024 }, { ...paper, id: "W4", isSeed: false }];
	const merged = { ...paper, records: [paper, ...versions] };
	assert.deepEqual(graphExportVersions([merged], undefined, emptyFilter(), "one", false).map(p => p.id), ["W1"]);
	assert.equal(graphExportVersions([merged], undefined, emptyFilter(), "all", false).length, 3);
	assert.equal(graphExportVersions([merged], undefined, { ...emptyFilter(), language: "fr" }, "all", false).length, 0);
	assert.deepEqual(graphExportVersions([merged], undefined, { ...emptyFilter(), language: "fr" }, "one", true).map(p => p.id), ["W1"]);
	assert.deepEqual(graphExportVersions([merged], undefined, { ...emptyFilter(), scrubYear: 2021 }, "all", false).map(p => p.id), ["W1", "W4"]);
	const projects: Record<string, ResearchProject> = {};
	updateProjectPaperState(projects, "W1", versions[0]!, { excluded: true });
	assert.deepEqual(graphExportVersions([merged], projects.W1, emptyFilter(), "all", false).map(p => p.id), ["W1", "W4"], "excluded versions never enter graph exports");
	const fields = { project: '项目 "A"', relation: "seed", status: "to-read" as const };
	const note = literatureMarkdown(special, "{{title}}\n{{project}}\n{{status}}", fields);
	assert.ok(note.includes(`title: ${JSON.stringify(special.title)}`));
	assert.ok(note.includes("rc-status: to-read"));
	assert.ok(note.includes(`${special.title}\n${fields.project}\nto-read`));
	assert.match(literatureMarkdown(merged, "", fields), /rc-doi-aliases: \[/);
	assert.ok(!/[\\/:*?"<>|]/.test(literatureFilename(special, "../{{title}}", fields)));
	assert.equal(JSON.stringify([paper, missing]), before, "exports never mutate source data");
	bindLanguage(() => "en");
	assert.ok(toMarkdownTable([missing]).startsWith("| Title | Authors |"));
	bindLanguage(() => "zh-CN");
	assert.ok(toMarkdownTable([missing]).startsWith("| 题名 | 作者 |"));
	bindLanguage(readHostLanguage);
}
